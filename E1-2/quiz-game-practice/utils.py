"""공통 입력 처리 유틸리티.

이 모듈은 아무것도 import 하지 않는다. (의존 구조의 맨 아래층)
"""


# ----------------------------------------------------------------------
# 숫자 입력
# ----------------------------------------------------------------------

def input_int(prompt, min_value, max_value):
    """min_value ~ max_value 범위의 정수를 입력받아 반환한다.

    공백 제거, 빈 입력, 숫자 변환 실패, 범위 밖 값을 모두 처리하고
    올바른 값이 들어올 때까지 다시 물어본다.
    """
    # 올바른 정수가 입력될 때까지 전체 검증을 반복함
    while True:
        # 입력 양쪽의 불필요한 공백을 제거함
        raw = input(prompt).strip()

        # 아무 내용도 없으면 안내 후 처음부터 다시 입력받음
        if raw == "":
            print(
                f"경고: 입력이 비어 있습니다. "
                f"{min_value}-{max_value} 사이의 숫자를 입력하세요."
            )
            continue

        # 입력 문자열을 정수로 변환하고, 문자는 다시 입력받음
        try:
            value = int(raw)
        except ValueError:
            print(
                f"경고: 잘못된 입력입니다. "
                f"{min_value}-{max_value} 사이의 숫자를 입력하세요."
            )
            continue

        # 정수라도 허용 범위를 벗어나면 다시 입력받음
        if value < min_value or value > max_value:
            print(f"경고: {min_value}-{max_value} 범위를 벗어났습니다. 다시 입력하세요.")
            continue

        # 모든 검증을 통과한 정수만 호출한 곳에 반환함
        return value


# ----------------------------------------------------------------------
# 문자열 입력
# ----------------------------------------------------------------------

def input_text(prompt):
    """앞뒤 공백을 제거하고 비어 있지 않은 문자열을 반환한다.

    빈 문자열이 입력되면 안내 메시지를 출력하고 다시 입력받는다.
    """
    # 비어 있지 않은 문자열이 입력될 때까지 반복함
    while True:
        # 입력 양쪽의 불필요한 공백을 제거함
        raw = input(prompt).strip()

        # 빈 입력이면 안내 후 처음부터 다시 입력받음
        if raw == "":
            print("경고: 내용을 입력해야 합니다.")
            continue

        # 검증을 통과한 문자열을 호출한 곳에 반환함
        return raw
